const daysAgo = (n: number) =>
  new Date(Date.now() - n * 86_400_000).toISOString().slice(0, 10);
const daysAhead = (n: number) =>
  new Date(Date.now() + n * 86_400_000).toISOString().slice(0, 10);

function verification(
  level: "full" | "partial" | "minimal",
  verifiedDaysAgo?: number,
): VerificationStatus {
  const base = { demo: true as const, verifiedOn: verifiedDaysAgo ? daysAgo(verifiedDaysAgo) : undefined };
  if (level === "full")
    return { ...base, identityVerified: true, phoneVerified: true, emailVerified: true, propertyDetailsVerified: true, locationConfirmed: true };
  if (level === "partial")
    return { ...base, identityVerified: false, phoneVerified: true, emailVerified: true, propertyDetailsVerified: true, locationConfirmed: false };
  return { ...base, identityVerified: false, phoneVerified: true, emailVerified: false, propertyDetailsVerified: false, locationConfirmed: false };
}

function owner(
  id: string,
  name: string,
  role: Owner["role"],
  level: "full" | "partial" | "minimal",
  responseTimeHours?: number,
): Owner {
  return {
    id,
    name,
    role,
    memberSince: "2026-03-01",
    responseTimeHours,
    verification: verification(level, level === "full" ? 12 : undefined),
  };
}

